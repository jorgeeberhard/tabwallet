//! The Password policy (`PasswordPolicy` in the glossary): the single place
//! that decides whether a new password is accepted. Sign-up, the password
//! reset and the profile all call [`check`]; nothing else judges a password.
//!
//! Pure on purpose: no HTTP, no SQL. The caller passes the password and the
//! e-mail and name of the account it is for.
//!
//! The rules, checked in this order (the first that fails is the answer):
//!
//! 1. **Length**: 10 to 128 characters (characters, not bytes).
//! 2. **Sequence or repetition** (`password_sequence`): `aaaaaaaaaa`,
//!    `abababababab`, `1234512345` (any block repeated at least twice),
//!    `1234567890`, `abcdefghij`, `zyxwvutsrqp`, a stretch of
//!    a keyboard row (`qwertyuiop`).
//! 3. **Common password** (`password_common`): the password is in the
//!    embedded list (`common_passwords.txt`).
//! 4. **Contains the e-mail** (`password_contains_email`).
//! 5. **Contains the name** (`password_contains_name`).
//!
//! There is no composition rule: no demand for capitals, digits or symbols.
//!
//! # How texts are compared
//!
//! Everything is compared *folded*: lowercased, with Portuguese accents
//! removed (`José` is `jose`, `ação` is `acao`).
//!
//! * **Common list and patterns** look at four versions of the folded
//!   password: as typed; without its *trailing* digits, symbols and spaces
//!   (the "stem": `Senha123!` is `senha`, `Qwerty@2024` is `qwerty`); and
//!   both of those again with the usual leet substitutions undone
//!   (`@`, `4` as `a`, `0` as `o`, `3` as `e`, `5` and `$` as `s`, `7` as
//!   `t`: `p@ssw0rd` is `password`). The list therefore needs the base words;
//!   the endings people append are handled here. The stem only counts for the
//!   patterns when it has at least 8 characters, so `abcd` plus six random
//!   digits is not a "sequence".
//! * **E-mail**: the part before the `@` (and, when it has a `+tag`, the part
//!   before the `+`), plus the whole address. The password and these are
//!   reduced to letters and digits only, so `bruno.lima`, `bruno_lima` and
//!   `BrunoLima` all find each other. Fragments shorter than 4 characters
//!   are ignored (`ana@...` does not forbid every password with "ana").
//! * **Name**: the whole name joined (`Ana Souza` is `anasouza`) and each word
//!   of it, again letters and digits only. Words shorter than 4 characters
//!   (`Ana`, `de`, `da`) are ignored; this is the "very short fragments"
//!   exception. A name that is empty (the account has not set one) forbids
//!   nothing.

use std::{collections::HashSet, sync::LazyLock};

pub const MIN_LEN: usize = 10;
/// Upper bound that keeps a huge body from becoming a huge Argon2 job.
pub const MAX_LEN: usize = 128;

/// E-mail and name fragments shorter than this are not searched for.
const MIN_PERSONAL_FRAGMENT: usize = 4;
/// A stem (password minus trailing digits and symbols) shorter than this is
/// not judged as a sequence or repetition.
const MIN_PATTERN_STEM: usize = 8;

/// Rows a password can be a stretch of, in either direction.
const KEYBOARD_ROWS: [&str; 4] = ["qwertyuiop[]", "asdfghjkl;'", "zxcvbnm,./", "1234567890-="];

/// The embedded list: one lowercase entry per line, `#` starts a comment.
/// Generated by `backend/scripts/generate-common-passwords.mjs`.
static COMMON: LazyLock<HashSet<&'static str>> = LazyLock::new(|| {
    include_str!("common_passwords.txt")
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .collect()
});

/// Why a password was refused. Each has a stable [`code`](Rejection::code)
/// that the front-end turns into a message.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Rejection {
    TooShort,
    TooLong,
    Common,
    Sequence,
    ContainsEmail,
    ContainsName,
}

impl Rejection {
    /// The stable code sent under the password field of the error response.
    pub fn code(self) -> &'static str {
        match self {
            Self::TooShort => "password_too_short",
            Self::TooLong => "password_too_long",
            Self::Common => "password_common",
            Self::Sequence => "password_sequence",
            Self::ContainsEmail => "password_contains_email",
            Self::ContainsName => "password_contains_name",
        }
    }
}

/// Who the password is for. `name` is empty when the account has none.
#[derive(Debug, Clone, Copy)]
pub struct Account<'a> {
    pub email: &'a str,
    pub name: &'a str,
}

/// Decides whether `password` is acceptable for `account`.
pub fn check(password: &str, account: Account<'_>) -> Result<(), Rejection> {
    let length = password.chars().count();
    if length < MIN_LEN {
        return Err(Rejection::TooShort);
    }
    if length > MAX_LEN {
        return Err(Rejection::TooLong);
    }
    let folded = fold(password);
    let variants = Variants::of(&folded);
    if variants.is_sequence_or_repetition() {
        return Err(Rejection::Sequence);
    }
    if variants.is_common() {
        return Err(Rejection::Common);
    }
    let letters_and_digits = alphanumeric(&folded);
    if email_fragments(account.email)
        .iter()
        .any(|fragment| letters_and_digits.contains(fragment.as_str()))
    {
        return Err(Rejection::ContainsEmail);
    }
    if name_fragments(account.name)
        .iter()
        .any(|fragment| letters_and_digits.contains(fragment.as_str()))
    {
        return Err(Rejection::ContainsName);
    }
    Ok(())
}

/// The versions of a folded password the list and the patterns look at.
struct Variants {
    /// As typed.
    whole: String,
    /// Without trailing digits, symbols and spaces.
    stem: String,
    /// `whole` and `stem` with leet substitutions undone.
    unleeted_whole: String,
    unleeted_stem: String,
}

impl Variants {
    fn of(folded: &str) -> Self {
        let stem = strip_trailing_non_letters(folded).to_string();
        Self {
            unleeted_whole: unleet(folded),
            unleeted_stem: unleet(&stem),
            whole: folded.to_string(),
            stem,
        }
    }

    fn is_common(&self) -> bool {
        [
            &self.whole,
            &self.stem,
            &self.unleeted_whole,
            &self.unleeted_stem,
        ]
        .into_iter()
        .any(|candidate| !candidate.is_empty() && COMMON.contains(candidate.as_str()))
    }

    fn is_sequence_or_repetition(&self) -> bool {
        let pattern = |text: &str| {
            is_repetition(text) || is_alphanumeric_run(text) || is_keyboard_stretch(text)
        };
        pattern(&self.whole)
            || (self.stem.chars().count() >= MIN_PATTERN_STEM && pattern(&self.stem))
    }
}

/// Lowercase, with the accents of Portuguese (and a few neighbours) removed.
fn fold(text: &str) -> String {
    text.chars()
        .flat_map(char::to_lowercase)
        .map(|c| match c {
            'á' | 'à' | 'â' | 'ã' | 'ä' | 'å' => 'a',
            'ç' => 'c',
            'é' | 'è' | 'ê' | 'ë' => 'e',
            'í' | 'ì' | 'î' | 'ï' => 'i',
            'ñ' => 'n',
            'ó' | 'ò' | 'ô' | 'õ' | 'ö' => 'o',
            'ú' | 'ù' | 'û' | 'ü' => 'u',
            'ý' | 'ÿ' => 'y',
            other => other,
        })
        .collect()
}

/// Only the letters and digits of an already folded text.
fn alphanumeric(folded: &str) -> String {
    folded.chars().filter(|c| c.is_alphanumeric()).collect()
}

fn strip_trailing_non_letters(text: &str) -> &str {
    text.trim_end_matches(|c: char| !c.is_alphabetic())
}

/// Undoes the usual character swaps (`p@ssw0rd` to `password`).
fn unleet(text: &str) -> String {
    text.chars()
        .map(|c| match c {
            '@' | '4' => 'a',
            '0' => 'o',
            '3' => 'e',
            '5' | '$' => 's',
            '7' => 't',
            other => other,
        })
        .collect()
}

/// One block repeated at least twice to fill the text (the last repetition
/// may be cut short): `aaaa`, `abab`, `123123`, `1234512345`. Any block up to
/// half the length counts, so a doubled word or number is refused too.
fn is_repetition(text: &str) -> bool {
    let chars: Vec<char> = text.chars().collect();
    (1..=chars.len() / 2).any(|block| (block..chars.len()).all(|i| chars[i] == chars[i % block]))
}

/// Each character follows the previous in the alphabet or among the digits,
/// all going up or all going down. Digits wrap (`9` then `0`, `0` then `9`).
fn is_alphanumeric_run(text: &str) -> bool {
    let chars: Vec<char> = text.chars().collect();
    if chars.len() < 2 || !chars.iter().all(char::is_ascii_alphanumeric) {
        return false;
    }
    let follows = |previous: char, next: char, step: i32| {
        if previous.is_ascii_digit() && next.is_ascii_digit() {
            let digit = |c: char| c as i32 - '0' as i32;
            (digit(previous) + step).rem_euclid(10) == digit(next)
        } else {
            previous.is_ascii_alphabetic()
                && next.is_ascii_alphabetic()
                && previous as i32 + step == next as i32
        }
    };
    [1, -1]
        .into_iter()
        .any(|step| chars.windows(2).all(|pair| follows(pair[0], pair[1], step)))
}

/// A stretch of one keyboard row, left to right or right to left.
fn is_keyboard_stretch(text: &str) -> bool {
    let backwards: String = text.chars().rev().collect();
    KEYBOARD_ROWS
        .iter()
        .any(|row| row.contains(text) || row.contains(backwards.as_str()))
}

/// What of the e-mail the password may not contain, as letters and digits.
fn email_fragments(email: &str) -> Vec<String> {
    let folded = fold(email);
    let local = folded.split('@').next().unwrap_or_default();
    let untagged = local.split('+').next().unwrap_or_default();
    [local, untagged, folded.as_str()]
        .into_iter()
        .map(alphanumeric)
        .filter(|fragment| fragment.chars().count() >= MIN_PERSONAL_FRAGMENT)
        .collect()
}

/// What of the name the password may not contain: the name joined and each
/// word of it, as letters and digits.
fn name_fragments(name: &str) -> Vec<String> {
    let folded = fold(name);
    let words = folded.split(|c: char| !c.is_alphanumeric());
    std::iter::once(alphanumeric(&folded))
        .chain(words.map(str::to_string))
        .filter(|fragment| fragment.chars().count() >= MIN_PERSONAL_FRAGMENT)
        .collect()
}
